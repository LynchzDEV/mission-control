  await studio.getByRole('textbox', { name: 'Command', exact: true }).fill(process.execPath)
  const checkArguments = studio.locator('.step-attachments').getByRole('textbox', { name: 'Arguments · one per line', exact: true })
  await checkArguments.fill('-e')
  await checkArguments.press('End')
  await checkArguments.press('Enter')
  await checkArguments.pressSequentially('process.stdout.write("acceptance okay")')
  assert.equal(await checkArguments.inputValue(), '-e\nprocess.stdout.write("acceptance okay")')
  await studio.getByRole('textbox', { name: 'Workflow name' }).fill('Custom browser workflow')
  const card = studio.locator('.react-flow__node').filter({ hasText: 'Custom browser checks' })
  const bounds = await card.boundingBox()
  assert(bounds)
  await page.mouse.move(bounds.x + 50, bounds.y + 20)
  await page.mouse.down()
  await page.mouse.move(bounds.x + 85, bounds.y + 60, { steps: 8 })
  await page.mouse.up()
  await studio.getByRole('button', { name: 'Save', exact: true }).click()
  await studio.getByText('Workflow saved. Existing runs keep their original version.').waitFor()
  await page.reload()
  await studio.locator('.saved-workflows').getByRole('button', { name: 'Custom browser workflow', exact: false }).click()
  assert.equal(await studio.locator('.flow-step').count(), 5)
  await studio.getByRole('button', { name: 'Run workflow', exact: true }).click()
  await studio.getByRole('textbox', { name: 'Run title', exact: true }).fill('Custom fixture browser run')
  await studio.getByRole('textbox', { name: 'Project folder', exact: true }).fill(repo)
