  await studio.getByText('Connection checked. No task was sent.').waitFor()
  await studio.getByRole('button', { name: 'Rules', exact: true }).click()
  await studio.getByText('Edit the core prompt', { exact: true }).click()
  await studio.getByRole('textbox', { name: 'Prompt template', exact: true }).fill('Updated team prompt\n{{core_rules}}\n{{workflow}}\n{{assignment}}')
  await studio.getByRole('button', { name: 'Save prompt', exact: true }).click()
  await studio.getByText('Core prompt saved for future runs.').waitFor()
  await studio.getByRole('button', { name: 'Workflows', exact: true }).click()
  await studio.locator('.saved-workflows').getByRole('button', { name: 'Custom browser workflow', exact: false }).click()
  await page.screenshot({ path: join(tmpdir(), 'mc-studio-desktop.png'), fullPage: true })
  await studio.getByRole('button', { name: 'Back to workflows', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
