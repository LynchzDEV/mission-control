  await page.locator('#term-cwd').fill(repo)
  const openedStandard = page.waitForResponse(response => response.url().endsWith('/api/terminals') && response.request().method() === 'POST')
  await page.locator('#term-form').getByRole('button', { name: 'Open terminal', exact: true }).click()
  const standardTerminal = await (await openedStandard).json()
