  await studio.getByRole('textbox', { name: 'Ask AI to change the workflow' }).fill('Add a testing step before final review')
  await studio.getByRole('button', { name: 'Update flow', exact: true }).click()
  await studio.getByText('Added a testing step', { exact: true }).first().waitFor({ timeout: 15000 })
  assert.equal(await studio.locator('.flow-step').count(), 5)
  await studio.getByRole('button', { name: 'Save', exact: true }).click()
  await studio.getByRole('button', { name: 'Back to workflows', exact: true }).click()
  await studio.getByRole('button', { name: 'Use the default workflow', exact: false }).click()
  await studio.getByRole('button', { name: 'Run workflow', exact: true }).click()
  await studio.getByRole('textbox', { name: 'Run title', exact: true }).fill('Default browser run')
  await studio.getByRole('textbox', { name: 'Project folder', exact: true }).fill(repo)
